/** Idiomes en què es publica cada ciutat. */
export function cityLangs(c: City): Lang[] {
  const local: Record<CC, Lang> = { es: 'es', pt: 'pt', fr: 'fr', it: 'it' }
  return [local[c.cc], ...(c.ca ? (['ca'] as Lang[]) : []), 'en']
}

export type Lang = 'ca' | 'es' | 'pt' | 'fr' | 'it' | 'en'
export const cityName = (c: City, lang: Lang) => c.n?.[lang] ?? c.name
